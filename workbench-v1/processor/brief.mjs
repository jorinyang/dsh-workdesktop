/**
 * `v1/processor/brief.mjs` —— **把一段话收成"一句话"**（用户第 5.1 / 6.1 条点名）。
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 用户原话
 *   · 5.1「**消息转待办：概括消息内容为一句话**，作为待办标题」
 *   · 6.1「**消息转日程：概括消息内容为一句话**，作为日程主题」
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 为什么不是"取前 N 个字"
 *
 *   原来那两处的写法是 `String(src.summary ?? src.raw ?? '').slice(0, 80)`
 *   —— 而 `summary` 本身就是**原文的截断**（`raw.slice(0, 60)`），
 *   所以结果是一段被切一半的话，末尾常常停在半句上：
 *     「@周勇（三闻） 已经沟通过 他个人还是倾向钉钉的会再去推动钉钉的，关于企业的话他们董事长考虑的点就是他」
 *   那不是"一句话"，是**断句**。
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 做法（**纯规则，不调模型**）
 *
 *   一、剥掉**不该进标题**的东西：@某人、表情短码、图片/文件标记、URL；
 *   二、取**第一句**（按中文句读 `。！？；` 与换行切）—— 一句话天然就是"第一句"；
 *   三、砍掉开头的**客套/应答语**（"好的""嗯""那个""就是"这类）——
 *      它们占着标题开头，却不含信息；
 *   四、还太长就**在标点处收**（不硬切在字中间），收不了才按长度截并加省略号；
 *   五、全空就返回空串，由调用方决定兜底文案（**不编一个假标题**）。
 *
 * ⚠️ 为什么不用模型：标题生成在**每次点击转换**时都会跑。
 *   用户点一下"转待办"要立刻看到结果，为它调一次模型（几秒到几十秒）不划算；
 *   而且这类"取第一句、去客套"的规则足够稳定 —— **能确定的事不要交给模型**。
 */

/** 不该进标题的东西（剥掉；顺序有讲究：先剥带括号的标记，再剥零散符号） */
export function stripNoise(s) {
  return String(s ?? '')
    // 图片/视频/语音/文件的机器标记（与 `pages.mjs#stripImageMark` 同一族形态）
    .replace(/\[(图片|视频|语音|文件)消息\]\(mediaId=[^)\s]*\)?/g, '')
    .replace(/mediaId=[^)\s]*/g, '')
    // @某人：`@张三`、`@杨瑒(月夜)`、`@张三（部门）`
    .replace(/@[^\s@，。！？；：、,.!?;:]{1,20}(?:[（(][^）)]{0,20}[）)])?/g, ' ')
    // 表情短码：`[傻笑]`、`[忍者]`（钉钉的表情就是这种方括号）
    .replace(/\[[^\]\s]{1,6}\]/g, ' ')
    // URL 与裸链接
    .replace(/https?:\/\/\S+/g, ' ')
    // 连续空白
    .replace(/\s{2,}/g, ' ')
    .trim();
}

/** 开头的客套/应答语（占着位置但不含信息） */
const OPENERS = [
  '好的好的', '好的', '好滴', '好得', '好嘞', '行吧', '行', '嗯嗯', '嗯', '哦哦', '哦',
  '那个', '这个', '就是', '然后', '另外', '还有', '对了', '诶', '哎', '喂',
  '稍等', '等我', '我看下', '我看一下', '收到',
  // ★ 2026-10-14 补（**真样例逼出来的**）：真样例收出来是
  //   「已经沟通过 他个人还是倾向钉钉的会再去推动钉钉的」——
  //   开头那个"已经沟通过"是**应答语**（回应对方上一句），不含任何新信息，
  //   却把真正的内容往后挤。这类"我做了某件没信息量的事"的说法一并归到开头剥掉。
  //   ⚠️ 只剥**开头**且后面跟分隔的：正文里出现"已经沟通过"不能动（那可能是关键交代）。
  '已经沟通过了', '已经沟通了', '已经沟通过', '沟通过了', '已经确认了', '已经确认过', '确认过了',
  '已经看过了', '已经看过', '看过了', '已经弄完了', '已经弄好', '弄好了', '已经发了', '发了',
  '已经处理了', '处理好了', '已经回复了', '回复过了', '已经安排了', '安排好了',
  '我知道了', '知道啦', '明白了', '了解', '了解啦',
];
export function stripOpeners(s) {
  let t = String(s ?? '').trim();
  // 反复剥：`好的，那个，我…` 这种连着来的
  for (let i = 0; i < 3; i += 1) {
    const before = t;
    for (const o of OPENERS) {
      // 只在**开头**且后面紧跟分隔或空白时才算客套（"行"不能吃掉"行业调研"）
      const re = new RegExp(`^${o}(?=[\\s，,。.、；;：:！!？?]|$)`);
      t = t.replace(re, '').replace(/^[\s，,。.、；;：:！!？?]+/, '');
    }
    if (t === before) break;
  }
  return t.trim();
}

/**
 * 把一段话收成一句话（用作标题/主题）。
 * @param {string} raw 原话
 * @param {{max?:number}} o `max` = 最长字数（默认 34），超出会在标点处收
 * @returns {string} 一句话；收不出东西时返回空串（**调用方自己决定兜底，这里不编**）
 */
export function briefTitle(raw, { max = 34 } = {}) {
  let t = stripOpeners(stripNoise(raw));
  if (t === '') return '';
  // 取第一句：中文句读 + 换行都算断句
  const first = t.split(/[。！？；\n\r]+/)[0];
  t = String(first ?? '').trim();
  if (t === '') return '';
  // 还是太长：先在**逗号**处收（保住一个完整的短句）
  if ([...t].length > max) {
    const parts = t.split(/[，,、]/);
    let acc = '';
    for (const p of parts) {
      const next = acc === '' ? p : `${acc}，${p}`;
      if ([...next].length > max) break;
      acc = next;
    }
    if ([...acc].length >= 8) t = acc;
    else {
      // 逗号处也收不了（一整句没逗号）⇒ 按长度截，**但要标出来截过**
      const chars = [...t];
      t = chars.slice(0, max).join('').replace(/[\s，,、；;：:]+$/, '') + '…';
    }
  }
  return t.trim();
}

/** 从原话里挑出**参与人**（`@某人` 剥出来的名字，去重、限量） */
export function pickParticipants(raw, { max = 6 } = {}) {
  const names = [];
  const re = /@([^\s@，。！？；：、,.!?;:]{1,20}?)(?:[（(][^）)]{0,20}[）)])?(?=[\s，。！？；：、,.!?;:]|$)/g;
  let m;
  while ((m = re.exec(String(raw ?? ''))) !== null) {
    const n = String(m[1] ?? '').trim();
    if (n && !names.includes(n)) names.push(n);
    if (names.length >= max) break;
  }
  return names;
}

/** 从原话里挑**地点**（只认明确的"在/于 + 地名"形态，不硬猜） */
export function pickPlace(raw) {
  const t = stripNoise(raw);
  const m = /(?:在|于)\s*([\u4e00-\u9fa5A-Za-z0-9（）()·\-]{2,20}?(?:会议室|大厦|中心|园区|酒店|楼|室|厅|馆|基地|现场|线上|腾讯会议|钉钉会议|飞书会议))/.exec(t);
  return m ? String(m[1]).trim() : null;
}

export async function selfTest() {
  const out = [];
  const chk = (id, desc, ok, detail = '') => out.push({ id, desc, ok: !!ok, detail: String(detail) });

  // 用**库里真实的那条**做样例（不是我编的），因为它正是原来断在半句的那种
  const real = '@周勇（三闻） 已经沟通过 他个人还是倾向钉钉的会再去推动钉钉的，关于企业的话他们董事长考虑的点就是他们';
  const b1 = briefTitle(real);
  chk('BR-1', '★★ 真样例收成一句话（不再是断在半句的截断）', b1.length > 0 && [...b1].length <= 34 && !b1.includes('@'), b1);
  chk('BR-2', '★ 剥掉 @某人（标题里不该带 @）', !briefTitle('@张三 @李四 明天把方案发我').includes('@'), briefTitle('@张三 @李四 明天把方案发我'));
  chk('BR-3', '★ 剥掉表情短码', !/\[.+\]/.test(briefTitle('[傻笑]这个我今晚弄完[忍者]')), briefTitle('[傻笑]这个我今晚弄完[忍者]'));
  chk('BR-4', '★ 剥掉开头客套（"好的""嗯""那个"）',
    !/^(好的|嗯|那个)/.test(briefTitle('好的，那个，明天上午十点对一下方案')), briefTitle('好的，那个，明天上午十点对一下方案'));
  chk('BR-5', '★ 只取**第一句**（第二句不进标题）', !briefTitle('方案我改完了。另外那个报价也发了。').includes('报价'), briefTitle('方案我改完了。另外那个报价也发了。'));
  chk('BR-6', '★ 太长时在**标点处**收（不硬切在字中间）', (() => {
    const b = briefTitle('这次培训我们准备把三个模块都过一遍，重点是接口那块，另外还要看一下权限配置，最后做个总结');
    return [...b].length <= 34 && !b.endsWith('…');
  })(), briefTitle('这次培训我们准备把三个模块都过一遍，重点是接口那块，另外还要看一下权限配置，最后做个总结'));
  chk('BR-7', '★ 一整句没标点时**标出被截过**（加省略号，不假装完整）', (() => {
    const b = briefTitle('这是一句特别特别长的没有任何标点的中文用来测试截断之后会不会加上省略号表示它被截过');
    return b.endsWith('…');
  })(), briefTitle('这是一句特别特别长的没有任何标点的中文用来测试截断之后会不会加上省略号表示它被截过'));
  chk('BR-8', '★ 空/纯噪声 ⇒ 返回空串（**不编一个假标题**）',
    briefTitle('') === '' && briefTitle('   ') === '' && briefTitle('[傻笑]') === '');
  chk('BR-9', '★ 客套词不会吃掉真词（"行业调研"的"行"不能当客套剥掉）',
    briefTitle('行业调研明天开始').startsWith('行业'), briefTitle('行业调研明天开始'));
  chk('BR-10', '★ 参与人从 `@` 里挑，带括号的也认', (() => {
    const p = pickParticipants('@张三 @李四（技术部） 明天开会');
    return p.includes('张三') && p.some((x) => x.startsWith('李四'));
  })(), pickParticipants('@张三 @李四（技术部） 明天开会').join('/'));
  chk('BR-11', '★ 地点只认明确形态（"在XX会议室"），**不硬猜**',
    pickPlace('明天在3楼会议室对一下') === '3楼会议室' && pickPlace('明天对一下方案') === null,
    String(pickPlace('明天在3楼会议室对一下')) + ' / ' + String(pickPlace('明天对一下方案')));
  chk('BR-12', '★ 纯规则：不调模型（无网络/无 spawn）', !/spawn|fetch|http/i.test(briefTitle.toString()));

  return { pass: out.filter((x) => x.ok).length, fail: out.filter((x) => !x.ok).length, details: out };
}
